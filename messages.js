'use strict';

// ボイスチャンネルの人数変化に応じてランダムに選ばれる通知文言の定義。
// LLMは使わず、ここに書いた定型文の配列からランダムに1つ選ぶだけ。
//
// 新しい文言を追加したい場合は、該当するカテゴリの配列に文字列を1つ足すだけでよい。
// 使えるプレースホルダ:
//   {count} … 在室人数
//   {names} … 在室メンバーの表示名を「、」で連結したもの
// {names} を含む文言は、メンバー名が取得できなかった場合には選ばれない。
// そのため各カテゴリには {names} を含まない文言を最低1つは残しておくこと。
//
// 組織に合わせて丸ごと書き換えて構わない。

module.exports = {
  // 在室0人（誰もいなくなった）
  empty: [
    'ボイスチャンネルは誰も居なくなりました',
    '通話が終わったみたいだね',
    '静かになっちゃった…また集まろうね',
  ],

  // 誰もいなかったところに最初の1人が来た
  firstJoin: [
    '{names} がボイスチャンネルに来ました！',
    '{names} が最初の一人目だぞ～',
    'ボイスチャンネルが空いたよ: {names}',
    'ボイスチャンネルに1人居ます',
  ],

  // 少人数（firstJoin/large以外の通常時）
  small: [
    'ボイスチャンネルに{count}人居ます: {names}',
    '{names} がボイスチャンネルにいるよ',
    'ボイスチャンネルに{count}人居ます',
  ],

  // 大人数（5人以上）
  large: [
    'ボイスチャンネルが賑わっているね～！{count}人: {names}',
    '大人数が集まっているね（{count}人）: {names}',
    'ボイスチャンネルに{count}人も集まっています',
  ],
};